-- Baseline schema, taken from the database the app shipped with (H2 SCRIPT dump),
-- plus the uniqueness and foreign-key checks the controller used to do by hand.

CREATE TABLE admin (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(45)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    user_role     VARCHAR(20)  NOT NULL CHECK (user_role IN ('Admin', 'Employee'))
);

CREATE TABLE course (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course      VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(200) NOT NULL,
    degree      VARCHAR(200) NOT NULL
);

CREATE TABLE student (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studentNum INTEGER      NOT NULL UNIQUE,
    semester   VARCHAR(100) NOT NULL,
    course     VARCHAR(100) NOT NULL,
    firstName  VARCHAR(100) NOT NULL,
    lastName   VARCHAR(100) NOT NULL,
    gender     ENUM('Male', 'Female', 'Other') NOT NULL,
    birthDate  DATE         NOT NULL,
    status     VARCHAR(100) NOT NULL,
    -- Path of the student's photo; '' means "no photo"
    image      VARCHAR(500) NOT NULL,
    added_on   DATE         NOT NULL
);

CREATE TABLE student_attendance (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT      NOT NULL REFERENCES student (id) ON DELETE CASCADE ON UPDATE CASCADE,
    course_id  INTEGER     NOT NULL REFERENCES course (id) ON UPDATE CASCADE,
    entry_time TIMESTAMP,
    exit_time  TIMESTAMP,
    status     VARCHAR(20) NOT NULL DEFAULT 'Absent' CHECK (status IN ('Present', 'Absent'))
);
